// Operators in JavaScript

// 1. Arithmetic Operators
let a = 10;
let b = 5;
console.log(a + b); // Output: 15
console.log(a - b); // Output: 5
console.log(a * b); // Output: 50
console.log(a / b); // Output: 2
console.log(a % b); // Output: 0
console.log(a ** b); // Output: 100000 (10 raised to the power of 5)
// 2. Assignment Operators
let c = 20;
c += 5; // Equivalent to c = c + 5
console.log(c); // Output: 25
c -= 10; // Equivalent to c = c - 10
console.log(c); // Output: 15
c *= 2; // Equivalent to c = c * 2
console.log(c); // Output: 30
c /= 3; // Equivalent to c = c / 3
console.log(c); // Output: 10
c %= 4; // Equivalent to c = c % 4
console.log(c); // Output: 2
c **= 3; // Equivalent to c = c ** 3
console.log(c); // Output: 8 (2 raised to the power of 3)        
// 3. Comparison Operators
console.log(a == b); // Output: false (loose equality, checks value)
console.log(a === b); // Output: false (strict equality, checks value and type)
console.log(a != b); // Output: true (loose inequality, checks value) 
console.log(a !== b); // Output: true (strict inequality, checks value and type)
console.log(a > b); // Output: true
console.log(a < b); // Output: false
console.log(a >= b); // Output: true
console.log(a <= b); // Output: false
// 4. Logical Operators
let x = true;  
let y = false;
console.log(x && y); // Output: false (logical AND)
console.log(x || y); // Output: true (logical OR)
console.log(!x); // Output: false (logical NOT)
console.log(!y); // Output: true (logical NOT)

